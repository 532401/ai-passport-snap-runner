#!/usr/bin/env python3
"""Generate/check Snap Runner's fixed UI character inventory and LVGL fonts.

Generation requires fontTools and npx (lv_font_conv 1.5.3). The lightweight
--check mode needs only Python; runtime/desktop probes check actual glyphs.
"""
import argparse
import hashlib
import json
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FONT = ROOT / "assets/fonts/NotoSansSC.ttf"


def inventory():
    text = (ROOT / "main/snap_ui.c").read_text()
    chars = set(chr(i) for i in range(32, 127))
    for literal in re.findall(r'"(?:[^"\\]|\\.)*"', text):
        chars.update(c for c in literal if ord(c) >= 128)
    return sorted(ord(c) for c in chars)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    points = inventory()
    expected = "// Generated by tools/snap_fonts.py; fixed application UI only.\n"
    expected += "static const uint32_t snap_glyphs[] = {\n    "
    expected += ", ".join(f"0x{p:X}" for p in points) + "\n};\n"
    header = ROOT / "main/snap_glyphs.h"
    manifest = ROOT / "assets/fonts/snap_fonts.json"
    if args.check:
        assert header.read_text() == expected, "UI text changed: regenerate fonts"
        saved = json.loads(manifest.read_text())
        assert saved["codepoints"] == points
        for name, digest in saved["sha256"].items():
            assert hashlib.sha256((ROOT / "assets/fonts" / name).read_bytes()).hexdigest() == digest
        print(f"Snap font inventory: {len(points)} code points, source/output hashes PASS")
        return
    from fontTools.ttLib import TTFont
    from fontTools import subset
    from fontTools.varLib.instancer import instantiateVariableFont
    cmap = TTFont(FONT).getBestCmap()
    missing = [f"U+{p:04X}" for p in points if p not in cmap]
    assert not missing, f"Source font missing: {missing}"
    header.write_text(expected)
    # The variable font defaults to a very thin weight. Freeze Medium explicitly
    # before conversion for legible antialiased strokes on the small LCD.
    static = instantiateVariableFont(TTFont(FONT), {"wght": 500}, inplace=True)
    selected = subset.Subsetter()
    selected.populate(unicodes=points)
    selected.subset(static)
    intermediate = ROOT / "build/font-source-medium.ttf"
    intermediate.parent.mkdir(exist_ok=True)
    static.save(intermediate)
    for size in (16, 22):
        subprocess.run([
            "npx", "--yes", "lv_font_conv@1.5.3", "--font", "build/font-source-medium.ttf",
            "--symbols", "".join(chr(p) for p in points), "--size", str(size),
            "--bpp", "4", "--format", "lvgl", "--no-compress", "--no-kerning",
            "--lv-font-name", f"snap_font_{size}", "--lv-include", "lvgl.h",
            "--output", str(ROOT / f"assets/fonts/snap_font_{size}.c"),
        ], check=True, cwd=ROOT)
    names = ("NotoSansSC.ttf", "snap_font_16.c", "snap_font_22.c")
    manifest.write_text(json.dumps({
        "source": "https://github.com/google/fonts/tree/main/ofl/notosanssc",
        "license": "SIL Open Font License 1.1 (OFL.txt)",
        "converter": "lv_font_conv 1.5.3", "sizes": [16, 22], "bpp": 4,
        "weight": 500,
        "codepoints": points,
        "sha256": {name: hashlib.sha256((ROOT / "assets/fonts" / name).read_bytes()).hexdigest() for name in names},
    }, indent=2) + "\n")
    print(f"Generated both fonts: {len(points)} verified source glyphs")


if __name__ == "__main__":
    main()
