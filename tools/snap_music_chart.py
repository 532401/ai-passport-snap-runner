#!/usr/bin/env python3
"""Build a sparse takeoff chart from the reviewed, recording-specific beat grid.

Generation and --check need only the standard library. Offline analysis is kept
separate: loud acoustic attacks are not substitutes for musical downbeats.
"""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PCM = ROOT / 'assets/music/mountain-king.pcm'
GRID = ROOT / 'assets/music/mountain-king-beats.json'
CHART = ROOT / 'assets/music/mountain-king-chart.json'
HEADER = ROOT / 'main/snap_chart_data.h'


def header(chart):
    lines = ['/* Generated by tools/snap_music_chart.py. Do not hand-edit. */',
             '#define SNAP_SONG_MS %dU' % chart['duration_ms'],
             'static const snap_chart_event_t snap_chart[] = {']
    for event in chart['events']:
        lines.append('    {%d, %d, %d, %d},' % tuple(event[k] for k in
                     ('jump_ms', 'width', 'height', 'kind')))
    return '\n'.join(lines + ['};', ''])


def generate(grid, grid_digest, raw):
    events = []
    for beat in grid['beats']:
        if beat['position'] != 1 or not beat['playable']:
            continue
        time_ms = round(beat['time_ms'] / 10) * 10
        previous = events[-1]['jump_ms'] if events else 0
        if time_ms < 3000 or time_ms - previous < 2500:
            continue
        pit = len(events) % 3 == 2
        events.append(dict(jump_ms=time_ms, bar=beat['bar'],
                           width=26 if pit else 12, height=0 if pit else 12,
                           kind=int(pit)))
    # Explicit coda accents take priority over an overlapping final regular cue.
    # They are acoustic events, not invented barlines in the irregular ending.
    accents = grid['coda_accents']
    if accents:
        first = round(accents[0]['time_ms'] / 10) * 10
        while events and first - events[-1]['jump_ms'] < 2500:
            events.pop()
    for accent in accents:
        time_ms = round(accent['time_ms'] / 10) * 10
        if events and time_ms - events[-1]['jump_ms'] < 2500:
            continue
        pit = len(events) % 3 == 2
        events.append(dict(jump_ms=time_ms, accent_id=accent['id'],
                           width=26 if pit else 12, height=0 if pit else 12,
                           kind=int(pit)))
    return dict(pcm_sha256=hashlib.sha256(raw).hexdigest(),
                beat_grid_sha256=grid_digest, sample_rate=16000,
                samples=len(raw) // 2, duration_ms=len(raw) * 1000 // 32000,
                min_interval_ms=2500,
                method='Reviewed recording-specific 4/4 downbeats; skip whole '
                       'bars until at least 2500 ms since the previous takeoff. '
                       'Coda uses separately localized isolated accents with the same '
                       'spacing floor. No constant-BPM extrapolation.',
                events=events)


def validate(chart, grid, grid_digest, raw):
    digest = hashlib.sha256(raw).hexdigest()
    assert grid['pcm_sha256'] == chart['pcm_sha256'] == digest, 'Audio changed: review beat grid'
    assert chart['beat_grid_sha256'] == grid_digest, 'Beat grid changed: rebuild chart'
    assert chart['samples'] * 2 == len(raw)
    assert chart['duration_ms'] == len(raw) * 1000 // 32000
    assert grid['meter'] == [4, 4]
    previous_time = -1
    previous_beat = None
    downbeats = {}
    for beat in grid['beats']:
        assert previous_time < beat['time_ms'] < chart['duration_ms']
        assert beat['position'] in (1, 2, 3, 4)
        assert type(beat['playable']) is bool
        if previous_beat:
            assert beat['position'] == previous_beat['position'] % 4 + 1
            assert beat['bar'] == previous_beat['bar'] + (beat['position'] == 1)
        if beat['position'] == 1 and beat['playable']:
            downbeats[beat['bar']] = beat['time_ms']
        previous_time, previous_beat = beat['time_ms'], beat
    accents = {}
    previous_time = grid['beats'][-1]['time_ms']
    for accent in grid['coda_accents']:
        assert previous_time < accent['time_ms'] < chart['duration_ms'] - 3000
        assert accent['id'] not in accents
        accents[accent['id']] = accent['time_ms']
        previous_time = accent['time_ms']
    previous = 0
    for event in chart['events']:
        assert event['jump_ms'] - previous >= 2500
        assert event['jump_ms'] < chart['duration_ms'] - 3000
        assert event['jump_ms'] % 10 == 0
        if 'accent_id' in event:
            assert 'bar' not in event, 'Coda accent must not invent a barline'
            assert event['accent_id'] in accents, 'Unknown coda accent'
            target = accents[event['accent_id']]
        else:
            assert event['bar'] in downbeats, 'Cue is not a playable downbeat'
            target = downbeats[event['bar']]
        assert abs(event['jump_ms'] - target) <= 5, 'Off-beat takeoff'
        assert event['kind'] in (0, 1)
        assert (event['width'], event['height']) == ((26, 0) if event['kind'] else (12, 12))
        previous = event['jump_ms']
    assert len(chart['events']) >= 30
    assert chart == generate(grid, grid_digest, raw), 'Chart selection is stale'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    raw, grid_raw = PCM.read_bytes(), GRID.read_bytes()
    grid, grid_digest = json.loads(grid_raw), hashlib.sha256(grid_raw).hexdigest()
    chart = json.loads(CHART.read_text()) if args.check else generate(grid, grid_digest, raw)
    validate(chart, grid, grid_digest, raw)
    if args.check:
        assert HEADER.read_text() == header(chart)
    else:
        CHART.write_text(json.dumps(chart, indent=2) + '\n')
        HEADER.write_text(header(chart))
    print('Music asset/beat grid/chart: %d musical cues, %d ms, %d bytes PASS' %
          (len(chart['events']), chart['duration_ms'], len(raw)))


if __name__ == '__main__':
    main()
